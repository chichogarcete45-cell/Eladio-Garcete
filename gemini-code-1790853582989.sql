CREATE TABLE componentes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  marca TEXT NOT NULL,
  cantidad INT NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
  estado TEXT NOT NULL CHECK (estado IN ('Disponible', 'En uso', 'Reparación', 'Baja')),
  descripcion TEXT,
  fecha_registro TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Habilitar Row Level Security (RLS)
ALTER TABLE componentes ENABLE ROW LEVEL SECURITY;

-- Política de lectura/escritura pública para evaluación del proyecto
CREATE POLICY "Acceso publico total" ON componentes 
FOR ALL USING (true) WITH CHECK (true);